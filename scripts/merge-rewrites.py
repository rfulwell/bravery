"""Merges Bravery's plaster rules into brave-core's rewrite/ tree.

Plaster allows one rule file per Chromium source file, and Brave keeps adding
its own. So Bravery's rules live in bravery-rewrite/, mirroring rewrite/, and
are merged at build time: Bravery's substitutions are appended to Brave's
committed rule file for the same source, or the file is created if Brave has
none. Starting from Brave's committed version (HEAD) makes this idempotent.

  merge-rewrites.py <patched brave-core dir>

Prints the rewrite/ paths it wrote, one per line, for `plaster.py apply`.
"""

import subprocess
import sys
from pathlib import Path

import yaml


def brave_version(brave_core, path):
    result = subprocess.run(['git', 'show', f'HEAD:{path}'], cwd=brave_core,
                            capture_output=True, text=True)
    return yaml.safe_load(result.stdout) if result.returncode == 0 else None


def main():
    brave_core = Path(sys.argv[1]).resolve()
    ours_root = brave_core / 'bravery-rewrite'
    for ours_path in sorted(ours_root.rglob('*.yaml')):
        relative = ours_path.relative_to(ours_root).as_posix()
        target = f'rewrite/{relative}'
        ours = yaml.safe_load(ours_path.read_text())
        merged = brave_version(brave_core, target) or {'substitutions': []}
        for key, value in ours.items():
            if key == 'substitutions':
                merged['substitutions'] = merged.get('substitutions', []) + value
            else:
                merged.setdefault(key, value)
        out = brave_core / target
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(
            '# Generated by Bravery: Brave\'s rules for this file followed by\n'
            f'# Bravery\'s from bravery-rewrite/{relative}.\n' +
            yaml.safe_dump(merged, sort_keys=False, allow_unicode=True,
                           width=1000))
        print(target)


if __name__ == '__main__':
    main()
